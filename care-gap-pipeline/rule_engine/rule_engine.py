    def service_information(
        member_id,
        measure_id
    ):

        h = get_service_history(
            member_id,
            measure_id
        )

        if h.empty:

            return {
                "service":
                    "No recorded service",

                "test":
                    "No recorded test",

                "date":
                    pd.NaT,

                "missed":
                    0,

                "completed":
                    0
            }

        h = h.sort_values(
            "service_date",
            ascending=False
        )

        completed = (
            h["status_lower"]
            == "completed"
        )

        missed = (
            h["status_lower"]
            == "missed"
        )

        # Find latest non-empty service
        service = "No recorded service"

        for x in h["service_name"]:

            if str(x).strip():
                service = str(x).strip()
                break

        # Find latest non-empty test
        test = "No recorded test"

        for x in h["test_name"]:

            if str(x).strip():
                test = str(x).strip()
                break

        date = (
            h["service_date"]
            .dropna()
            .max()
            if h["service_date"].notna().any()
            else pd.NaT
        )

        return {

            "service": service,

            "test": test,

            "date": date,

            "missed": int(
                missed.sum()
            ),

            "completed": int(
                completed.sum()
            )
        }

    # ============================================================
    # 22. DETERMINE CARE GAP
    # ============================================================

    def is_care_gap(
        row,
        measure_id
    ):

        # --------------------------------------------------------
        # C12 - Blood Sugar Controlled
        # --------------------------------------------------------

        if measure_id == "C12":

            h = get_service_history(
                row["member_id"],
                "C12"
            )

            if h.empty:
                return True

            completed = h[
                h["status_lower"]
                == "completed"
            ]

            if completed.empty:
                return True

            # If result is uncontrolled, gap
            result = (
                completed["result"]
                .fillna("")
                .astype(str)
                .str.lower()
            )

            if result.str.contains(
                "uncontrolled|not controlled|poor",
                regex=True
            ).any():

                return True

            return False

        # --------------------------------------------------------
        # C13 - Kidney Health Evaluation
        # --------------------------------------------------------

        if measure_id == "C13":

            h = get_service_history(
                row["member_id"],
                "C13"
            )

            if h.empty:
                return True

            completed_tests = h[
                h["status_lower"]
                == "completed"
            ]

            if completed_tests.empty:
                return True

            text = (
                completed_tests["test_name"]
                .fillna("")
                .astype(str)
                .str.lower()
            )

            # Need evidence of both kidney evaluation
            # components
            has_kidney = text.str.contains(
                "kidney|egfr",
                regex=True
            ).any()

            has_urine = text.str.contains(
                "urine|uacr|albumin",
                regex=True
            ).any()

            return not (
                has_kidney and has_urine
            )

        # --------------------------------------------------------
        # C14 - Blood Pressure
        # --------------------------------------------------------

        if measure_id == "C14":

            h = get_service_history(
                row["member_id"],
                "C14"
            )

            if h.empty:
                return True

            completed = h[
                h["status_lower"]
                == "completed"
            ]

            if completed.empty:
                return True

            return False

        # --------------------------------------------------------
        # C19 - Statin Therapy for CVD
        # --------------------------------------------------------

        if measure_id == "C19":

            m = med_groups.get(
                str(row["member_id"]),
                pd.DataFrame()
            )

            if m.empty:
                return True

            statins = m[
                m["med_class"]
                == "cholesterol"
            ]

            return statins.empty

        # --------------------------------------------------------
        # C18 - Readmission
        # --------------------------------------------------------

        if measure_id == "C18":

            # There is no reliable hospitalization/readmission
            # event in the supplied MEMBER_HISTORY.
            #
            # Therefore do NOT fabricate a care gap.
            return False

        # --------------------------------------------------------
        # D08 - Diabetes Medication
        # --------------------------------------------------------

        if measure_id == "D08":

            s = medication_stats(
                row["member_id"],
                "D08"
            )

            return (
                s["active"] == 0
                or
                s["adherence"] < 0.80
                or
                s["days_since_fill"] > 60
            )

        # --------------------------------------------------------
        # D09 - Hypertension Medication
        # --------------------------------------------------------

        if measure_id == "D09":

            s = medication_stats(
                row["member_id"],
                "D09"
            )

            return (
                s["active"] == 0
                or
                s["adherence"] < 0.80
                or
                s["days_since_fill"] > 60
            )

        # --------------------------------------------------------
        # D10 - Cholesterol Medication
        # --------------------------------------------------------

        if measure_id == "D10":

            s = medication_stats(
                row["member_id"],
                "D10"
            )

            return (
                s["active"] == 0
                or
                s["adherence"] < 0.80
                or
                s["days_since_fill"] > 60
            )

        # --------------------------------------------------------
        # D11 - MTM
        # --------------------------------------------------------

        if measure_id == "D11":

            h = history_groups.get(
                str(row["member_id"]),
                pd.DataFrame()
            )

            if h.empty:
                return False

            text = (
                h.fillna("")
                .astype(str)
                .agg(
                    " ".join,
                    axis=1
                )
                .str.lower()
            )

            mtm = text.str.contains(
                "mtm|medication therapy management|cmr|comprehensive medication review",
                regex=True
            )

            # Only evaluate members for whom MTM evidence exists
            if not mtm.any():
                return False

            completed = text.str.contains(
                "cmr|comprehensive medication review",
                regex=True
            )

            return not completed.any()

        # --------------------------------------------------------
        # D12 - Statin Use in Diabetes
        # --------------------------------------------------------

        if measure_id == "D12":

            m = med_groups.get(
                str(row["member_id"]),
                pd.DataFrame()
            )

            if m.empty:
                return True

            statins = m[
                m["med_class"]
                == "cholesterol"
            ]

            return statins.empty

        return False

    # ============================================================
    # 23. OUTPUT COLUMNS
    # ============================================================

    OUTPUT_COLUMNS = [

        "patient_id",
        "member_name",
        "plan_id",
        "care_gap",
        "age",
        "gender",
        "condition",
        "condition_code",
        "part",
        "measure_id",
        "measure_type",
        "measure_weight",
        "service_name",
        "test_name",
        "performance_value",
        "measure_star",
        "enrollment_status",
        "enrollment_tenure_days",
        "missed_service_count",
        "completed_service_count",
        "days_since_last_service",
        "previous_intervention_count",
        "previous_success_rate",
        "previous_phone_count",
        "phone_success_rate",
        "previous_sms_count",
        "sms_success_rate",
        "previous_email_count",
        "email_success_rate",
        "active_medication_count",
        "missed_refill_count",
        "medication_adherence_rate",
        "days_since_last_fill",
        "refill_number",
        "intervention_type"
    ]

    # ============================================================
    # 24. BUILD RULE ENGINE
    # ============================================================

    results = []

    diagnostics = []

    for _, row in base.iterrows():

        member_id = str(
            row["member_id"]
        )

        plan_id = str(
            row["plan_id"]
        )

        condition = str(
            row["condition"]
        ).strip()

        for _, measure in cms.iterrows():

            measure_id = str(
                measure["measure_id"]
            )

            measure_name = str(
                measure["measure_name"]
            )

            part = str(
                measure["part"]
            )

            # ----------------------------------------------------
            # CONDITION ELIGIBILITY
            # ----------------------------------------------------

            allowed_conditions = (
                condition_rules
                .get(
                    measure_id,
                    []
                )
            )

            eligible = any(
                condition.lower()
                == allowed.lower()
                for allowed
                in allowed_conditions
            )

            if not eligible:

                continue

            # ----------------------------------------------------
            # PLAN BENEFIT SUPPORT
            # ----------------------------------------------------

            supported = plan_supports_measure(
                plan_id,
                measure_id
            )

            # Do not force unsupported benefit
            if not supported:

                continue

            # ----------------------------------------------------
            # C18 HAS NO PATIENT-LEVEL DATA
            # ----------------------------------------------------

            if measure_id == "C18":

                continue

            # ----------------------------------------------------
            # CHECK CARE GAP
            # ----------------------------------------------------

            gap = is_care_gap(
                row,
                measure_id
            )

            if not gap:

                continue

            # ----------------------------------------------------
            # SERVICE INFORMATION
            # ----------------------------------------------------

            info = service_information(
                member_id,
                measure_id
            )

            # For medication measures, use meaningful
            # service/test names even when no previous
            # service exists.

            medication_service_names = {

                "D08": (
                    "Diabetes Medication Adherence",
                    "Medication Refill"
                ),

                "D09": (
                    "Hypertension Medication Adherence",
                    "Medication Refill"
                ),

                "D10": (
                    "Cholesterol Medication Adherence",
                    "Statin Refill"
                ),

                "D11": (
                    "Medication Therapy Management",
                    "Comprehensive Medication Review"
                ),

                "D12": (
                    "Statin Therapy",
                    "Statin Prescription Fill"
                )
            }

            if measure_id in medication_service_names:

                service_name, test_name = (
                    medication_service_names[
                        measure_id
                    ]
                )

            else:

                service_name = info["service"]

                test_name = info["test"]

            # ----------------------------------------------------
            # DAYS SINCE SERVICE
            # ----------------------------------------------------

            if pd.notna(info["date"]):

                days_since_service = max(
                    0,
                    (
                        REFERENCE_DATE
                        -
                        info["date"]
                    ).days
                )

            else:

                days_since_service = 0

            # ----------------------------------------------------
            # INTERVENTION
            # ----------------------------------------------------

            istats = intervention_stats(
                member_id
            )

            intervention_type = (
                istats["latest"]
            )

            # ----------------------------------------------------
            # MEDICATION
            # ----------------------------------------------------

            medstats = medication_stats(
                member_id,
                measure_id
            )

            # ----------------------------------------------------
            # PERFORMANCE
            # ----------------------------------------------------

            perf = performance_lookup.get(
                (
                    plan_id,
                    measure_id
                )
            )

            if perf is not None:

                performance_value = pd.to_numeric(
                    perf.get(
                        "performance_value",
                        0
                    ),
                    errors="coerce"
                )

                measure_star = pd.to_numeric(
                    perf.get(
                        "measure_star",
                        0
                    ),
                    errors="coerce"
                )

                # IMPORTANT:
                # Performance table has weight.
                # Output must be measure_weight.

                measure_weight = pd.to_numeric(
                    perf.get(
                        "weight",
                        measure.get(
                            "weight",
                            1
                        )
                    ),
                    errors="coerce"
                )

            else:

                performance_value = 0
                measure_star = 0

                measure_weight = pd.to_numeric(
                    measure.get(
                        "weight",
                        1
                    ),
                    errors="coerce"
                )

            if pd.isna(performance_value):
                performance_value = 0

            if pd.isna(measure_star):
                measure_star = 0

            if pd.isna(measure_weight):
                measure_weight = 1

            # ----------------------------------------------------
            # ENROLLMENT TENURE
            # ----------------------------------------------------

            start_date = row[
                "enrollment_start_date"
            ]

            if pd.notna(start_date):

                tenure = max(
                    0,
                    (
                        REFERENCE_DATE
                        -
                        start_date
                    ).days
                )

            else:

                tenure = 0

            # ----------------------------------------------------
            # BUILD 34-ATTRIBUTE RECORD
            # ----------------------------------------------------

            results.append({

                "patient_id":
                    member_id,

                "member_name":
                    str(row.get("member_name", "")),

                "plan_id":
                    plan_id,

                "care_gap":
                    measure_name,

                "age":
                    row["age"],

                "gender":
                    row["gender"],

                "condition":
                    row["condition"],

                "condition_code":
                    row["condition_code"],

                "part":
                    part,

                "measure_id":
                    measure_id,

                "measure_type":
                    measure["measure_type"],

                "measure_weight":
                    float(
                        measure_weight
                    ),

                "service_name":
                    service_name,

                "test_name":
                    test_name,

                "performance_value":
                    float(
                        performance_value
                    ),

                "measure_star":
                    float(
                        measure_star
                    ),

                "enrollment_status":
                    row["enrollment_status"],

                "enrollment_tenure_days":
                    int(tenure),

                "missed_service_count":
                    int(info["missed"]),

                "completed_service_count":
                    int(info["completed"]),

                "days_since_last_service":
                    int(
                        days_since_service
                    ),

                "previous_intervention_count":
                    int(
                        istats["count"]
                    ),

                "previous_success_rate":
                    float(
                        istats["success"]
                    ),

                "previous_phone_count":
                    int(
                        istats["phone"]
                    ),

                "phone_success_rate":
                    float(
                        istats["phone_success"]
                    ),

                "previous_sms_count":
                    int(
                        istats["sms"]
                    ),

                "sms_success_rate":
                    float(
                        istats["sms_success"]
                    ),

                "previous_email_count":
                    int(
                        istats["email"]
                    ),

                "email_success_rate":
                    float(
                        istats["email_success"]
                    ),

                "active_medication_count":
                    int(
                        medstats["active"]
                    ),

                "missed_refill_count":
                    int(
                        medstats["missed"]
                    ),

                "medication_adherence_rate":
                    float(
                        medstats["adherence"]
                    ),

                "days_since_last_fill":
                    int(
                        medstats["days_since_fill"]
                    ),

                "refill_number":
                    int(
                        medstats["refill"]
                    ),

                "intervention_type":
                    intervention_type
            })

    # ============================================================
    # 25. CREATE FINAL DATAFRAME
    # ============================================================

    output = pd.DataFrame(
        results
    )

    # Force exact 34 columns
    output = output[
        OUTPUT_COLUMNS
    ].copy()

    # ============================================================
    # 26. REMOVE DUPLICATE PATIENT + MEASURE
    # ============================================================

    output = output.drop_duplicates(
        subset=[
            "patient_id",
            "plan_id",
            "measure_id"
        ]
    ).reset_index(
        drop=True
    )

    # ============================================================
    # 27. NO NULL VALUES
    # ============================================================

    text_columns = [
        "patient_id",
        "member_name",
        "plan_id",
        "care_gap",
        "gender",
        "condition",
        "condition_code",
        "part",
        "measure_id",
        "measure_type",
        "service_name",
        "test_name",
        "enrollment_status",
        "intervention_type"
    ]

    for c in text_columns:

        output[c] = (
            output[c]
            .fillna("Unknown")
            .astype(str)
            .str.strip()
        )

    numeric_columns = [
        "age",
        "measure_weight",
        "performance_value",
        "measure_star",
        "enrollment_tenure_days",
        "missed_service_count",
        "completed_service_count",
        "days_since_last_service",
        "previous_intervention_count",
        "previous_success_rate",
        "previous_phone_count",
        "phone_success_rate",
        "previous_sms_count",
        "sms_success_rate",
        "previous_email_count",
        "email_success_rate",
        "active_medication_count",
        "missed_refill_count",
        "medication_adherence_rate",
        "days_since_last_fill",
        "refill_number"
    ]

    for c in numeric_columns:

        output[c] = pd.to_numeric(
            output[c],
            errors="coerce"
        ).fillna(0)

    # ============================================================
    # 28. FINAL VALIDATION
    # ============================================================

    print("\n")
    print("=" * 70)
    print("FINAL RULE ENGINE RESULT")
    print("=" * 70)

    print(
        "Total records:",
        len(output)
    )

    print(
        "Total attributes:",
        len(output.columns)
    )

    print(
        "\nExpected attributes: 34"
    )

    print(
        "\nNull values:"
    )

    nulls = output.isna().sum()

    print(
        nulls[nulls > 0]
    )

    print(
        "\nCare gap distribution:"
    )

    if len(output) > 0:

        print(
            output[
                "care_gap"
            ].value_counts()
        )

    else:

        print(
            "WARNING: ZERO RECORDS"
        )

    print(
        "\nPlan distribution:"
    )

    if len(output) > 0:

        print(
            output[
                "plan_id"
            ].value_counts()
        )

    # ============================================================
    # 29. CARE GAP COUNT
    # ============================================================

    if len(output) > 0:

        care_gap_count = (
            output
            .groupby(
                [
                    "plan_id",
                    "part",
                    "measure_id",
                    "care_gap"
                ]
            )
            .size()
            .reset_index(
                name="care_gap_count"
            )
        )

        plan_count = (
            output
            .groupby(
                "plan_id"
            )
            .size()
            .reset_index(
                name="total_care_gap_count"
            )
        )

    else:

        care_gap_count = pd.DataFrame(
            columns=[
                "plan_id",
                "part",
                "measure_id",
                "care_gap",
                "care_gap_count"
            ]
        )

        plan_count = pd.DataFrame(
            columns=[
                "plan_id",
                "total_care_gap_count"
            ]
        )

    # ============================================================
    # 30. SAVE EXCEL
    # ============================================================

    if save_path is not None:
        with pd.ExcelWriter(
            save_path,
            engine="openpyxl"
        ) as writer:

            output.to_excel(
                writer,
                sheet_name="RULE_ENGINE_OUTPUT",
                index=False
            )

            care_gap_count.to_excel(
                writer,
                sheet_name="CARE_GAP_COUNT",
                index=False
            )

            plan_count.to_excel(
                writer,
                sheet_name="PLAN_CARE_GAP_COUNT",
                index=False
            )

        print("Saved:", save_path)

    return output


