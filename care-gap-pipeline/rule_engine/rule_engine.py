    def intervention_stats(member_id):

        h = history_groups.get(
            str(member_id),
            pd.DataFrame()
        )

        if h.empty:

            return {
                "count": 0,
                "success": 0,
                "phone": 0,
                "phone_success": 0,
                "sms": 0,
                "sms_success": 0,
                "email": 0,
                "email_success": 0,
                "latest": "No previous intervention"
            }

        h = h[
            h["intervention_lower"].isin(
                [
                    "phone call",
                    "sms",
                    "email"
                ]
            )
        ].copy()

        if h.empty:

            return {
                "count": 0,
                "success": 0,
                "phone": 0,
                "phone_success": 0,
                "sms": 0,
                "sms_success": 0,
                "email": 0,
                "email_success": 0,
                "latest": "No previous intervention"
            }

        def success(row):

            return int(
                row["outcome_lower"]
                == "completed"
            )

        h["success"] = h.apply(
            success,
            axis=1
        )

        phone = h[
            h["intervention_lower"]
            == "phone call"
        ]

        sms = h[
            h["intervention_lower"]
            == "sms"
        ]

        email = h[
            h["intervention_lower"]
            == "email"
        ]

        latest = (
            h.sort_values(
                "service_date",
                ascending=False
            )
            .iloc[0]["intervention_type"]
        )

        return {

            "count":
                len(h),

            "success":
                round(
                    h["success"].mean(),
                    4
                ),

            "phone":
                len(phone),

            "phone_success":
                round(
                    phone["success"].mean()
                    if len(phone)
                    else 0,
                    4
                ),

            "sms":
                len(sms),

            "sms_success":
                round(
                    sms["success"].mean()
                    if len(sms)
                    else 0,
                    4
                ),

            "email":
                len(email),

            "email_success":
                round(
                    email["success"].mean()
                    if len(email)
                    else 0,
                    4
                ),

            "latest":
                str(latest)
        }

