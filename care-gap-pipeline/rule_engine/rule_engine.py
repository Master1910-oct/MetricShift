    def medication_stats(
        member_id,
        measure_id
    ):

        m = med_groups.get(
            str(member_id),
            pd.DataFrame()
        )

        if m.empty:

            return {
                "active": 0,
                "missed": 0,
                "adherence": 0,
                "days_since_fill": 0,
                "refill": 0
            }

        required_class = None

        if measure_id in ["D08"]:
            required_class = "diabetes"

        elif measure_id in ["D09"]:
            required_class = "hypertension"

        elif measure_id in ["D10", "D12"]:
            required_class = "cholesterol"

        if required_class is not None:

            m = m[
                m["med_class"] == required_class
            ]

        if m.empty:

            return {
                "active": 0,
                "missed": 0,
                "adherence": 0,
                "days_since_fill": 0,
                "refill": 0
            }

        m = m.sort_values("fill_date")

        latest_fill = m["fill_date"].max()

        days_since_fill = max(
            0,
            (REFERENCE_DATE - latest_fill).days
        )

        refill = pd.to_numeric(
            m["refill_number"],
            errors="coerce"
        ).fillna(0).max()

        missed = 0
        observed = 0
        adherent = 0

        for med_name, g in m.groupby(
            "medication_name"
        ):

            g = g.sort_values(
                "fill_date"
            )

            dates = list(
                g["fill_date"].dropna()
            )

            supplies = list(
                pd.to_numeric(
                    g["days_supply"],
                    errors="coerce"
                ).fillna(30)
            )

            if len(dates) == 1:

                observed += 1
                adherent += 1

            for i in range(
                len(dates) - 1
            ):

                gap = (
                    dates[i + 1]
                    -
                    dates[i]
                ).days

                expected = supplies[i]

                observed += 1

                if gap <= expected + 7:
                    adherent += 1
                else:
                    missed += 1

        adherence = (
            adherent / observed
            if observed > 0
            else 0
        )

        return {

            "active":
                int(
                    m["medication_name"]
                    .nunique()
                ),

            "missed":
                int(missed),

            "adherence":
                round(
                    adherence,
                    4
                ),

            "days_since_fill":
                int(days_since_fill),

            "refill":
                int(refill)
        }

    # ============================================================
